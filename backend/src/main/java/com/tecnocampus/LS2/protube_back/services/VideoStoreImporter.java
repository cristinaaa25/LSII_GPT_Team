package com.tecnocampus.LS2.protube_back.services;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.tecnocampus.LS2.protube_back.domain.Comment;
import com.tecnocampus.LS2.protube_back.domain.User;
import com.tecnocampus.LS2.protube_back.domain.Video;
import com.tecnocampus.LS2.protube_back.dto.StoreVideoJson;
import com.tecnocampus.LS2.protube_back.repository.CommentRepository;
import com.tecnocampus.LS2.protube_back.repository.UserRepository;
import com.tecnocampus.LS2.protube_back.repository.VideoRepository;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Service;
import org.springframework.transaction.PlatformTransactionManager;
import org.springframework.transaction.support.TransactionTemplate;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Instant;
import java.util.ArrayList;
import java.util.List;
import java.util.UUID;
import java.util.regex.Pattern;
import java.util.stream.Collectors;
import java.util.stream.Stream;

/**
 * Imports the videos generated by {@code tooling/videoGrabber} ({@code <id>.json} files in the store folder)
 * into the database. Already imported videos (same store id) are skipped, so it is safe to run on every startup.
 */
@Service
public class VideoStoreImporter {

    private static final Logger LOG = LoggerFactory.getLogger(VideoStoreImporter.class);

    private static final Pattern STORE_JSON = Pattern.compile("\\d+\\.json");
    // Placeholder users cannot log in: this is not a valid password hash
    static final String NO_PASSWORD = "!";
    static final String PLACEHOLDER_EMAIL_DOMAIN = "@placeholder.protube.local";
    static final String UNKNOWN_USER = "unknown";
    private static final int MAX_USERNAME = 50;
    private static final int MAX_TEXT = 255;

    private final VideoRepository videoRepository;
    private final UserRepository userRepository;
    private final CommentRepository commentRepository;
    private final ObjectMapper objectMapper;
    private final TransactionTemplate transactionTemplate;

    public VideoStoreImporter(VideoRepository videoRepository, UserRepository userRepository,
                              CommentRepository commentRepository, ObjectMapper objectMapper,
                              PlatformTransactionManager transactionManager) {
        this.videoRepository = videoRepository;
        this.userRepository = userRepository;
        this.commentRepository = commentRepository;
        this.objectMapper = objectMapper;
        this.transactionTemplate = new TransactionTemplate(transactionManager);
    }

    /**
     * @return number of videos imported in this run (skipped and invalid files are not counted)
     */
    public int importAll(Path storeDir) {
        if (!Files.isDirectory(storeDir)) {
            LOG.warn("Video store {} is not a directory, nothing to import", storeDir);
            return 0;
        }
        List<Path> files;
        try (Stream<Path> stream = Files.list(storeDir)) {
            files = stream
                    .filter(p -> STORE_JSON.matcher(p.getFileName().toString()).matches())
                    .sorted()
                    .toList();
        } catch (IOException e) {
            LOG.error("Cannot list video store {}", storeDir, e);
            return 0;
        }

        int imported = 0;
        for (Path file : files) {
            if (importFile(file)) {
                imported++;
            }
        }
        LOG.info("Imported {} new videos from {} ({} json files found)", imported, storeDir, files.size());
        return imported;
    }

    // Each file is imported in its own transaction so one broken file does not abort the whole import
    boolean importFile(Path file) {
        StoreVideoJson json;
        try {
            json = objectMapper.readValue(Files.readString(file, StandardCharsets.UTF_8), StoreVideoJson.class);
        } catch (IOException e) {
            LOG.warn("Skipping unreadable video file {}: {}", file, e.getMessage());
            return false;
        }
        if (json.id() == null || json.title() == null) {
            LOG.warn("Skipping video file {}: missing id or title", file);
            return false;
        }
        if (videoRepository.existsByStoreId(json.id())) {
            LOG.debug("Video {} already imported, skipping", json.id());
            return false;
        }
        transactionTemplate.executeWithoutResult(status -> persist(json));
        return true;
    }

    private void persist(StoreVideoJson json) {
        StoreVideoJson.Meta meta = json.meta();
        String authorName = json.user() != null ? json.user() : meta != null ? meta.channel() : null;

        Video video = new Video(
                truncate(json.title(), MAX_TEXT),
                meta != null ? meta.description() : null,
                json.id() + ".mp4",
                json.id() + ".webp",
                json.duration(),
                json.width(),
                json.height(),
                findOrCreatePlaceholderUser(authorName));
        video.setStoreId(json.id());
        if (json.timestamp() != null) {
            video.setCreatedAt(Instant.ofEpochSecond(json.timestamp()));
        }
        if (meta != null) {
            video.setViewCount(orZero(meta.viewCount()));
            video.setLikeCount(orZero(meta.likeCount()));
            video.setCategories(cleanList(meta.categories()));
            video.setTags(cleanList(meta.tags()));
        }
        videoRepository.save(video);

        if (meta == null || meta.comments() == null) {
            return;
        }
        for (StoreVideoJson.StoreComment c : meta.comments()) {
            if (c.text() == null || c.text().isBlank()) {
                continue;
            }
            Comment comment = new Comment(c.text(), video, findOrCreatePlaceholderUser(c.author()));
            if (c.timestamp() != null) {
                comment.setCreatedAt(Instant.ofEpochSecond(c.timestamp()));
            }
            commentRepository.save(comment);
        }
    }

    User findOrCreatePlaceholderUser(String name) {
        String username = (name == null || name.isBlank()) ? UNKNOWN_USER : truncate(name.strip(), MAX_USERNAME);
        return userRepository.findByUsername(username)
                .orElseGet(() -> userRepository.save(new User(username, placeholderEmail(username), NO_PASSWORD)));
    }

    // Deterministic and unique per username, always shorter than the 100-char column
    static String placeholderEmail(String username) {
        return UUID.nameUUIDFromBytes(username.getBytes(StandardCharsets.UTF_8)) + PLACEHOLDER_EMAIL_DOMAIN;
    }

    private static List<String> cleanList(List<String> values) {
        if (values == null) {
            return new ArrayList<>();
        }
        return values.stream()
                .filter(v -> v != null && !v.isBlank())
                .map(v -> truncate(v, MAX_TEXT))
                .distinct()
                .collect(Collectors.toCollection(ArrayList::new));
    }

    private static long orZero(Long value) {
        return value != null ? value : 0L;
    }

    private static String truncate(String value, int max) {
        return value.length() <= max ? value : value.substring(0, max);
    }
}
