-- Private user playlists and their ordered video entries.
-- "Watch later" is created on first use per user by the application and protected against rename/delete.
CREATE TABLE playlists (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_playlists_owner FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uq_playlists_owner_name UNIQUE (owner_id, name)
);

CREATE TABLE playlist_videos (
    playlist_id BIGINT NOT NULL,
    video_id BIGINT NOT NULL,
    added_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_playlist_videos PRIMARY KEY (playlist_id, video_id),
    CONSTRAINT fk_playlist_videos_playlist FOREIGN KEY (playlist_id) REFERENCES playlists (id) ON DELETE CASCADE,
    CONSTRAINT fk_playlist_videos_video FOREIGN KEY (video_id) REFERENCES videos (id) ON DELETE CASCADE
);

CREATE INDEX idx_playlists_owner_id ON playlists (owner_id);
CREATE INDEX idx_playlist_videos_video_id ON playlist_videos (video_id);
CREATE INDEX idx_playlist_videos_playlist_added ON playlist_videos (playlist_id, added_at, video_id);
